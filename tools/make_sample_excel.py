def _header_block(ws, title: str, ncols: int) -> int:
    ws.cell(row=1, column=1, value=ORG).font = Font(bold=True, size=12)
    ws.cell(row=2, column=1, value=title).font = Font(bold=True, size=12)
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncols)
    return 4


def _table(ws, start: int, headers, rows, widths, money_cols=(), total=None):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=start, column=i, value=h)
        c.font, c.fill, c.border = Font(bold=True), HEAD, BORDER
        c.alignment = Alignment(horizontal="center", vertical="center",
                                wrap_text=True)
        ws.column_dimensions[c.column_letter].width = widths[i - 1]
    for r, row in enumerate(rows, start + 1):
        for i, v in enumerate(row, 1):
            c = ws.cell(row=r, column=i, value=v)
            c.border = BORDER
            if isinstance(v, date):
                c.number_format = "DD.MM.YYYY"
            if i in money_cols:
                c.number_format = "#,##0.00"
    if total:
        r = start + len(rows) + 1
        ws.cell(row=r, column=1, value="Итого").font = Font(bold=True)
        col, value = total
        c = ws.cell(row=r, column=col, value=value)
        c.font, c.number_format = Font(bold=True), "#,##0.00"
    ws.freeze_panes = ws.cell(row=start + 1, column=1)


def build(dest: str, seed: int = 26) -> None:
    rnd = random.Random(seed)
    os.makedirs(dest, exist_ok=True)
    opening = date(2026, 7, 1)

    # 1. Сотрудники
    wb = Workbook(); ws = wb.active; ws.title = "Сотрудники"
    s = _header_block(ws, "Список сотрудников производственного участка", 4)
    _table(ws, s, ["№", "ФИО", "Должность", "Телефон"],
           [(i, *w) for i, w in enumerate(WORKERS, 1)], [5, 36, 32, 20])
    wb.save(os.path.join(dest, "Сотрудники.xlsx"))

    # 2. Объекты
    wb = Workbook(); ws = wb.active; ws.title = "Объекты"
    s = _header_block(ws, "Реестр объектов 2026 г.", 8)
    _table(ws, s, ["Код объекта", "Наименование объекта", "Адрес", "Заказчик",
                   "Сумма договора, руб.", "Статус", "Начало", "Окончание"],
           OBJECTS, [12, 58, 34, 28, 18, 13, 12, 12], money_cols=(5,),
           total=(5, sum(o[4] for o in OBJECTS)))
    wb.save(os.path.join(dest, "Объекты_2026.xlsx"))

    # 3. Справочник материалов с остатками
    wb = Workbook(); ws = wb.active; ws.title = "Остатки"
    s = _header_block(ws, f"Ведомость остатков материалов на {opening:%d.%m.%Y}", 9)
    rows = [(i, m[0], m[1], m[2], m[3], m[4], m[5], m[4] * m[5], m[6])
            for i, m in enumerate(MATERIALS, 1)]
    _table(ws, s, ["№", "Артикул", "Наименование", "Категория", "Ед. изм.",
                   "Цена, руб.", "Остаток", "Сумма, руб.", "Мин. остаток"],
           rows, [5, 10, 42, 26, 9, 12, 10, 14, 12], money_cols=(6, 8),
           total=(8, sum(r[7] for r in rows)))
    ws.cell(row=s + len(rows) + 3, column=2,
            value="Кладовщик ____________ Пономарёва О.В.")
    wb.save(os.path.join(dest, f"Материалы_остатки_на_{opening:%d.%m.%Y}.xlsx"))

    # 4-5. Движение за сентябрь - начало октября
    stock = {m[0]: m[5] for m in MATERIALS}
    price = {m[0]: m[4] for m in MATERIALS}
    by_cat = {}
    for m in MATERIALS:
        by_cat.setdefault(m[2], []).append(m)

    receipts, issues = [], []
    day = opening
    rec_no, req_no = 1842, 1
    while day <= date(2026, 10, 2):
        if day.weekday() < 5:
            # Приход: примерно два раза в неделю, по одной категории
            if day.weekday() == 0 or (day.weekday() == 3 and rnd.random() < 0.4):
                cat = rnd.choice(list(SUPPLIERS))
                doc = f"УПД {rec_no}"
                rec_no += rnd.randint(7, 40)
                for m in rnd.sample(by_cat[cat], k=min(len(by_cat[cat]), rnd.randint(2, 5))):
                    q = max(1, round(m[6] * rnd.uniform(0.9, 2.0)))
                    if m[3] in ("м", "м²"):
                        q = int(round(q / 6.0) * 6) or 6
                    p = round(price[m[0]] * rnd.uniform(0.97, 1.06), 2)
                    receipts.append((day, doc, SUPPLIERS[cat], m[0], m[1], m[3], q, p))
                    stock[m[0]] += q
            # Расход: требования на объекты в работе
            for obj_code, cats in OBJECT_PROFILE.items():
                obj = next(o for o in OBJECTS if o[0] == obj_code)
                if not obj[6] <= day <= obj[7] or rnd.random() < 0.45:
                    continue
                doc = f"ТР-{day:%m%d}-{req_no:02d}"
                req_no += 1
                cat = rnd.choice(cats)
                for m in rnd.sample(by_cat[cat], k=min(len(by_cat[cat]), rnd.randint(1, 3))):
                    avail = stock[m[0]]
                    if avail <= 0:
                        continue
                    want = avail * rnd.uniform(0.1, 0.35)
                    q = round(want, 1) if m[3] in ("м", "кг", "л", "м²") else int(want)
                    if q <= 0:
                        continue
                    issues.append((day, doc, obj_code, m[0], m[1], m[3], q,
                                   rnd.choice(RECEIVERS[obj_code])))
                    stock[m[0]] -= q
        day += timedelta(days=1)
        if day.weekday() == 0:
            req_no = 1

    wb = Workbook(); ws = wb.active; ws.title = "Приход"
    s = _header_block(ws, "Журнал поступления материалов, июль - октябрь 2026 г.", 9)
    rows = [(r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], round(r[6] * r[7], 2))
            for r in receipts]
    _table(ws, s, ["Дата", "Накладная", "Поставщик", "Артикул", "Наименование",
                   "Ед. изм.", "Кол-во", "Цена, руб.", "Сумма, руб."],
           rows, [12, 12, 30, 10, 42, 9, 9, 12, 14], money_cols=(8, 9),
           total=(9, round(sum(r[8] for r in rows), 2)))
    wb.save(os.path.join(dest, "Приход_материалов_июль-октябрь_2026.xlsx"))

    wb = Workbook(); ws = wb.active; ws.title = "Расход"
    s = _header_block(ws, "Журнал выдачи материалов на объекты (требования), "
                          "июль - октябрь 2026 г.", 8)
    _table(ws, s, ["Дата", "Требование", "Объект", "Артикул", "Наименование",
                   "Ед. изм.", "Кол-во", "Получил"],
           issues, [12, 14, 11, 10, 42, 9, 9, 32])
    wb.save(os.path.join(dest, "Расход_на_объекты_июль-октябрь_2026.xlsx"))

    print(f"Готово: {dest}\n  приход строк {len(receipts)}, расход строк {len(issues)}")


if __name__ == "__main__":
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    build(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "sample_data"))
