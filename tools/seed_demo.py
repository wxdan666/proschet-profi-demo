def main(folder: str) -> None:
    reset_database()
    for r in importer.import_folder(folder):
        print(r.summary())
        for e in r.errors:
            print("   ", e)
    staff = {w.name.split()[0]: w.id for w in workers.list_workers()}
    for code, text, cost, status, team in ORDERS:
        obj = objects.find_by_code(code)
        o = orders.create_order(text, obj.id, cost)
        orders.update_order(o.id, status, cost, [staff[t] for t in team])
    print(f"Заявок создано: {len(ORDERS)}")


